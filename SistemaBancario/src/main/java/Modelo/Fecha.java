package Modelo;

/**
 *
 * @author Titoelgato
 */
public class Fecha {
    private int dia;
    private int mes;
    private int ano;

    public Fecha(int dia, int mes, int ano) {
        this.dia = dia;
        this.mes = mes;
        this.ano = ano;
    }

    public int getDia() {
        return dia;
    }

    public int getMes() {
        return mes;
    }

    public int getAno() {
        return ano;
    }
   public String toString(){
       return "dia:"+ dia + "mes"+ mes + "año";
   }
}
